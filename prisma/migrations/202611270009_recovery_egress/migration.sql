CREATE OR REPLACE FUNCTION public.recovery_payment_item_log_change() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
 IF OLD.status IS DISTINCT FROM NEW.status OR OLD.url IS DISTINCT FROM NEW.url THEN
 INSERT INTO public.recovery_payment_item_changes(job_id,item_id) VALUES(NEW.job_id,NEW.id);
 END IF;
 RETURN NULL;
END; $$;
DROP TRIGGER IF EXISTS recovery_payment_item_ordered ON public.recovery_payment_items;
