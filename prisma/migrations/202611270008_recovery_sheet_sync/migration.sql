BEGIN;
CREATE TABLE IF NOT EXISTS public.recovery_sheet_changes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lead_id uuid NOT NULL, old_month text, new_month text
);
ALTER TABLE public.recovery_sheet_changes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.recovery_sheet_changes FROM anon, authenticated;
-- Acquire BEFORE row locks, so change IDs commit in order even across concurrent
-- writers. Worker-only lock/updated_at writes do not take this lock or emit changes.
CREATE OR REPLACE FUNCTION public.recovery_sheet_write_lock() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(18731, 20261127);
 RETURN NULL;
END;
$$;
CREATE OR REPLACE FUNCTION public.recovery_sheet_log_change() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
 IF TG_OP = 'UPDATE' AND
   (to_jsonb(NEW) - ARRAY['updated_at','link_change_token','link_change_until']) =
   (to_jsonb(OLD) - ARRAY['updated_at','link_change_token','link_change_until']) THEN
   RETURN NULL;
 END IF;
 INSERT INTO public.recovery_sheet_changes(lead_id, old_month, new_month)
 VALUES (CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END,
   CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE OLD.selected_month END,
   CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE NEW.selected_month END);
 RETURN NULL;
END;
$$;
DROP TRIGGER IF EXISTS recovery_sheet_ordered_writes ON public.recovery_leads;
CREATE TRIGGER recovery_sheet_ordered_writes BEFORE INSERT OR DELETE OR UPDATE OF
 timestamp, student_name, student_phone, student_email, student_college_email,
 executive_name, amount_mentioned, program_plan, domain, selected_month, referrals,
 payment_status, lead_status, comments, amount_paid, remaining_amount, payment_links,
 assigned_to, created_at, paid_at, registration_amount, uploaded_by, upload_id,
 filename, source_row, assigned_by, assigned_at
 ON public.recovery_leads FOR EACH STATEMENT EXECUTE FUNCTION public.recovery_sheet_write_lock();
DROP TRIGGER IF EXISTS recovery_sheet_changes ON public.recovery_leads;
CREATE TRIGGER recovery_sheet_changes AFTER INSERT OR UPDATE OR DELETE
 ON public.recovery_leads FOR EACH ROW EXECUTE FUNCTION public.recovery_sheet_log_change();
COMMIT;
